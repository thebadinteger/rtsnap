func makeQuantTables(q uint8) [][]byte {
	var scale int
	if q < 50 {
		scale = 5000 / int(q)
	} else {
		scale = 200 - 2*int(q)
	}

	tables := make([][]byte, 2)
	tables[0] = make([]byte, 64)
	tables[1] = make([]byte, 64)

	for i := 0; i < 64; i++ {
		v := (lumaQuantizers[i]*scale + 50) / 100
		if v > 255 {
			v = 255
		} else if v == 0 {
			v = 1
		}
		tables[0][i] = byte(v)

		v = (chromaQuantizers[i]*scale + 50) / 100
		if v > 255 {
			v = 255
		} else if v == 0 {
			v = 1
		}
		tables[1][i] = byte(v)
	}
	return tables
}

