// reassemble jpeg frame from rtp packet
func (d *MJPEGDepacketizer) Decode(pkt *Packet) ([]byte, error) {
	buf := pkt.Payload
	if len(buf) < 8 {
		return nil, fmt.Errorf("mjpeg packet too short")
	}

	offset := int(uint32(buf[1])<<16 | uint32(buf[2])<<8 | uint32(buf[3]))
	jpegType := buf[4]
	q := buf[5]
	w := int(buf[6]) * 8
	h := int(buf[7]) * 8
	buf = buf[8:]

	var restartInterval uint16
	if jpegType >= 64 {
		if len(buf) < 4 {
			return nil, fmt.Errorf("missing restart marker header")
		}
		restartInterval = binary.BigEndian.Uint16(buf[:2])
		buf = buf[4:]
	}

	if d.hasSeq && pkt.SequenceNumber == d.lastSeq {
		return nil, nil
	}
	gap := d.hasSeq && pkt.SequenceNumber-d.lastSeq != 1
	d.lastSeq = pkt.SequenceNumber
	d.hasSeq = true

	if offset == 0 {
		d.fragments = d.fragments[:0]
		d.fragmentsLen = 0
		d.width = w
		d.height = h
		d.jpegType = jpegType
		d.q = q
		d.restartInt = restartInterval
		d.hasFirstPacket = true

		if q >= 128 {
			if len(buf) < 4 {
				return nil, fmt.Errorf("missing quant table header")
			}
			tableLen := int(binary.BigEndian.Uint16(buf[2:4]))
			buf = buf[4:]
			if len(buf) < tableLen {
				return nil, fmt.Errorf("truncated quant tables")
			}
			tablesData := buf[:tableLen]
			buf = buf[tableLen:]

			d.quantTables = nil
			for len(tablesData) >= 64 {
				t := make([]byte, 64)
				copy(t, tablesData[:64])
				d.quantTables = append(d.quantTables, t)
				tablesData = tablesData[64:]
			}
		} else {
			d.quantTables = makeQuantTables(q)
		}

		f := make([]byte, len(buf))
		copy(f, buf)
		d.fragments = append(d.fragments, f)
		d.fragmentsLen = len(f)
	} else {
		if !d.hasFirstPacket || gap || offset != d.fragmentsLen {
			d.fragments = d.fragments[:0]
			d.fragmentsLen = 0
			d.hasFirstPacket = false
			return nil, nil
		}
		if d.fragmentsLen+len(buf) > d.maxBytes() {
			d.fragments = d.fragments[:0]
			d.fragmentsLen = 0
			d.hasFirstPacket = false
			return nil, fmt.Errorf("mjpeg frame too large")
		}
		f := make([]byte, len(buf))
		copy(f, buf)
		d.fragments = append(d.fragments, f)
		d.fragmentsLen += len(f)
	}

	if !pkt.Marker {
		return nil, nil
	}

	var out []byte

	out = append(out, 0xFF, 0xD8)

	if len(d.quantTables) > 0 {
		dqtLen := 2 + len(d.quantTables)*(1+64)
		out = append(out, 0xFF, 0xDB, byte(dqtLen>>8), byte(dqtLen))
		for id, tbl := range d.quantTables {
			out = append(out, byte(id))
			out = append(out, tbl...)
		}
	}

	out = append(out, 0xFF, 0xC0)
	out = append(out, 0x00, 0x11)
	out = append(out, 0x08)
	out = append(out, byte(d.height>>8), byte(d.height))
	out = append(out, byte(d.width>>8), byte(d.width))
	out = append(out, 0x03)

	subH, subV := byte(1), byte(1)
	if d.jpegType == 0 {
		subH = 2
	} else if d.jpegType == 1 {
		subH = 2
		subV = 2
	}
	out = append(out, 0x01, (subH<<4)|subV, 0x00)
	out = append(out, 0x02, 0x11, 0x01)
	out = append(out, 0x03, 0x11, 0x01)

	writeDHT := func(class, id byte, lens, symbols []byte) {
		l := 2 + 1 + len(lens) + len(symbols)
		out = append(out, 0xFF, 0xC4, byte(l>>8), byte(l))
		out = append(out, (class<<4)|id)
		out = append(out, lens...)
		out = append(out, symbols...)
	}
	writeDHT(0, 0, lumDcCodeLens, lumDcSymbols)
	writeDHT(1, 0, lumAcCodeLens, lumAcSymbols)
	writeDHT(0, 1, chmDcCodeLens, chmDcSymbols)
	writeDHT(1, 1, chmAcCodeLens, chmAcSymbols)

	if d.restartInt > 0 {
		out = append(out, 0xFF, 0xDD, 0x00, 0x04, byte(d.restartInt>>8), byte(d.restartInt))
	}

	out = append(out, 0xFF, 0xDA, 0x00, 0x0C, 0x03)
	out = append(out, 0x01, 0x00, 0x02, 0x11, 0x03, 0x11)
	out = append(out, 0x00, 0x3F, 0x00)

	for _, f := range d.fragments {
		out = append(out, f...)
	}

	if len(out) < 2 || out[len(out)-2] != 0xFF || out[len(out)-1] != 0xD9 {
		out = append(out, 0xFF, 0xD9)
	}

	d.fragments = d.fragments[:0]
	d.fragmentsLen = 0
	d.hasFirstPacket = false

	return out, nil
}
