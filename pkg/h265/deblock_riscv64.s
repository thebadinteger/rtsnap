#define LOAD8(addr, t, Vd) \
	VLE8V    (addr), t \
	VZEXTVF2 t, Vd

#define CLIPC(v, base, c, t0, t1) \
	VSUBVV c, base, t0 \
	VADDVV c, base, t1 \
	VMAXVV t0, v, v    \
	VMINVV t1, v, v

#define CLAMP(v, hi) \
	VMAXVX X0, v, v \
	VMINVX hi, v, v

